#!/usr/bin/env python3
"""Evidence-only source diagnostics; never performs lossy decoding."""
from __future__ import annotations
import hashlib, json, random, sys, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = [
    ("Lexique 3.83", ROOT / "data/raw/Lexique383.tsv"),
    ("Dicollecte/Grammalecte Hunspell archive", ROOT / "data/raw/hunspell-french-dictionaries-v7.7.zip"),
    ("Lefff 2.1 gzip", ROOT / "data/raw/lefff-2.1.txt.gz"),
]
SENTINELS = ("été", "français", "cœur", "garçon", "où", "à")

def inspect(path: Path, label: str, out: list[str]) -> bytes | None:
    out.append(f"\n## Source: {label}")
    out.append(f"Path: {path.relative_to(ROOT)}")
    if not path.is_file():
        out.append("STATUS: unavailable (file was not downloaded)")
        return None
    raw = path.read_bytes()
    out.append(f"Size bytes: {len(raw)}")
    out.append(f"SHA-256: {hashlib.sha256(raw).hexdigest()}")
    out.append(f"Starts with UTF-8 BOM: {'yes' if raw.startswith(bytes.fromhex('efbbbf')) else 'no'}")
    out.append(f"First 120 bytes hex: {raw[:120].hex(' ')}")
    out.append(f"Bytes >= 0x80: {sum(byte >= 0x80 for byte in raw)}")
    if label == "Lexique 3.83":
        try:
            decoded = raw.decode("utf-8-sig", errors="strict")
            out.append("Strict UTF-8 decode succeeds: yes")
            out.append("Lexique source sentinel presence: " + json.dumps({s: s.casefold() in decoded.casefold() for s in SENTINELS}, ensure_ascii=False, sort_keys=True))
        except UnicodeDecodeError as exc:
            out.append(f"Strict UTF-8 decode succeeds: no ({exc})")
    else:
        out.append("Container bytes are not text-decoded; compressed/archive payloads are inspected separately below.")
    return raw

def main() -> int:
    out = ["Pilot v3", "# Last-run source and pilot diagnostics", "", "This file is generated by GitHub Actions even when the import fails.", "No lossy decoding is used."]
    raw_files = {}
    for label, path in FILES:
        raw_files[label] = inspect(path, label, out)
    lefff_status_file = ROOT / "data/raw/lefff-download-status.txt"
    if lefff_status_file.is_file():
        out.append(lefff_status_file.read_text(encoding="utf-8", errors="strict").strip())
    zip_path = ROOT / "data/raw/hunspell-french-dictionaries-v7.7.zip"
    out.append("\n## Hunspell archive inventory and .aff evidence")
    if raw_files.get("Dicollecte/Grammalecte Hunspell archive") is None:
        out.append("Archive unavailable; no members can be inspected.")
    else:
        try:
            with zipfile.ZipFile(zip_path) as zf:
                for info in zf.infolist():
                    out.append(f"FILE {info.filename} | size={info.file_size}")
                affs = [info for info in zf.infolist() if info.filename.lower().endswith(".aff")]
                dics = [info for info in zf.infolist() if info.filename.lower().endswith(".dic")]
                if not affs:
                    out.append("No .aff files found.")
                set_by_stem = {}
                for info in affs:
                    data = zf.read(info.filename)
                    if data.startswith(bytes.fromhex("efbbbf")):
                        data = data[3:]
                    text = data.decode("utf-8-sig", errors="strict")
                    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
                    out.append(f"\nAFF: {info.filename} | size={info.file_size} | strict UTF-8: yes")
                    out.append("First 5 lines (BOM stripped; CRLF normalized):")
                    out.extend("  " + line for line in lines[:5])
                    set_lines = [line for line in lines if line.lstrip().lower().startswith("set ") or line.lstrip().lower() == "set"]
                    out.append("SET lines:")
                    out.extend("  " + line for line in set_lines) if set_lines else out.append("  no SET line")
                    set_match = next((__import__("re").match(r"^\s*SET\s+([^\s#]+)", line, __import__("re").I) for line in lines if __import__("re").match(r"^\s*SET\s+([^\s#]+)", line, __import__("re").I)), None)
                    if set_match:
                        set_by_stem[info.filename.rsplit(".", 1)[0]] = set_match.group(1)
                if not dics:
                    out.append("No .dic files found.")
                for info in dics:
                    stem = info.filename.rsplit(".", 1)[0]
                    declared = set_by_stem.get(stem)
                    out.append(f"\nDIC: {info.filename} | size={info.file_size} | paired .aff SET={declared or 'missing'}")
                    if not declared:
                        out.append("DIC strict decoding: not attempted because the paired .aff has no SET declaration.")
                        continue
                    try:
                        codec = __import__("codecs").lookup(declared).name
                        text = zf.read(info.filename).decode(codec, errors="strict")
                        out.append(f"DIC strict decoding using declared SET {declared} ({codec}): yes")
                        out.append("DIC sentinel presence: " + json.dumps({s: s.casefold() in text.casefold() for s in SENTINELS}, ensure_ascii=False, sort_keys=True))
                    except (UnicodeError, LookupError) as exc:
                        out.append(f"DIC strict decoding using declared SET {declared}: no ({type(exc).__name__}: {exc})")
        except (OSError, zipfile.BadZipFile) as exc:
            out.append(f"Archive inspection error: {type(exc).__name__}: {exc}")
    out.append("\n## Encoding decisions and Lefff codec probes")
    lex_path = ROOT / "data/raw/Lexique383.tsv"
    if lex_path.is_file():
        try:
            payload = lex_path.read_bytes()
            decoded = payload.decode("utf-8-sig", errors="strict")
            out.append("Lexique 3.83: UTF-8 confirmed by strict decoding plus non-ASCII bytes" if any(b >= 0x80 for b in payload) else "Lexique 3.83: encoding unconfirmed (strict UTF-8 succeeds but no non-ASCII bytes)")
            present = {s: s.casefold() in decoded.casefold() for s in ("été", "français", "cœur", "garçon", "où", "noël", "à", "œuf")}
            out.append("Lexique exact sentinel presence: " + json.dumps(present, ensure_ascii=False, sort_keys=True))
            out.append("Lexique note: sentinel presence is informational only; no requirement that cœur or any other rare sentinel occur.")
            out.append("Lexique source forbidden-marker check: " + ("no U+FFFD or \"Ã\" found" if not any(marker in decoded for marker in ("\ufffd", "Ã")) else "ERROR: forbidden U+FFFD or \"Ã\" found"))
        except (OSError, UnicodeError) as exc:
            out.append(f"Lexique encoding decision unavailable: {type(exc).__name__}: {exc}")
    lefff_path = ROOT / "data/raw/lefff-2.1.txt.gz"
    lefff_probe = {}
    if lefff_path.is_file():
        try:
            payload = __import__("gzip").decompress(lefff_path.read_bytes())
            codecs_to_test = ("utf-8", "iso-8859-1", "iso-8859-15", "cp1252")
            for codec in codecs_to_test:
                try:
                    decoded = payload.decode(codec, errors="strict")
                    lefff_probe[codec] = {
                        "strict_decode_succeeds": True,
                        "cœur_intact": "cœur" in decoded.casefold(),
                        "œuf_intact": "œuf" in decoded.casefold()
                    }
                except UnicodeDecodeError as exc:
                    lefff_probe[codec] = {"strict_decode_succeeds": False, "error": str(exc),
                                          "cœur_intact": False, "œuf_intact": False}
            byte_patterns = {
                "UTF-8 cœur": bytes.fromhex("63 c5 93 75 72"), "UTF-8 œuf": bytes.fromhex("c5 93 75 66"),
                "ISO-8859-15 cœur": bytes.fromhex("63 bd 75 72"), "ISO-8859-15 œuf": bytes.fromhex("bd 75 66"),
                "cp1252 cœur": bytes.fromhex("63 9c 75 72"), "cp1252 œuf": bytes.fromhex("9c 75 66")
            }
            byte_counts = {label: payload.lower().count(pattern) for label, pattern in byte_patterns.items()}
            out.append("Lefff strict decoding / sentinel results:")
            for codec, result in lefff_probe.items():
                out.append(f"  {codec}: strict_decode_succeeds={result['strict_decode_succeeds']}; cœur_intact={result['cœur_intact']}; œuf_intact={result['œuf_intact']}" + (f"; error={result['error']}" if "error" in result else ""))
            out.append("Lefff byte evidence for œ encodings: " + json.dumps(byte_counts, ensure_ascii=False, sort_keys=True))
            out.append("Expected limitation: ISO-8859-1 cannot represent œ; failure to preserve œ in cœur/œuf under Latin-1 is expected, not a codec error.")
            candidates = []
            if lefff_probe.get("utf-8", {}).get("cœur_intact") and lefff_probe.get("utf-8", {}).get("œuf_intact"):
                candidates.append("utf-8")
            if lefff_probe.get("iso-8859-15", {}).get("cœur_intact") and lefff_probe.get("iso-8859-15", {}).get("œuf_intact") and byte_counts["ISO-8859-15 cœur"] and byte_counts["ISO-8859-15 œuf"]:
                candidates.append("iso-8859-15")
            if lefff_probe.get("cp1252", {}).get("cœur_intact") and lefff_probe.get("cp1252", {}).get("œuf_intact") and byte_counts["cp1252 cœur"] and byte_counts["cp1252 œuf"]:
                candidates.append("cp1252")
            out.append(f"Lefff evidence-based decision: {candidates[0] if len(candidates)==1 else 'unavailable'}; decisive candidates={candidates!r}")
        except (OSError, ValueError) as exc:
            out.append(f"Lefff encoding probes failed: {type(exc).__name__}: {exc}")
    else:
        out.append("Lefff encoding probes unavailable: source file missing.")
    out.append("Dicollecte/Hunspell encoding: each paired .aff file declares SET UTF-8; dictionary decoding uses that declared codec.")
    out.append("\n## Encoding policy")
    out.append("Lefff decision requires one unique codec candidate preserving both cœur and œuf and matching the corresponding characteristic byte sequences. ISO-8859-1's missing œ is expected.")
    pilot = ROOT / "data/pilot-300.json"
    checks = ROOT / "data/cross-checks-300.json"
    out.append("\n## Pilot and cross-check result")
    if pilot.is_file():
        try:
            rows = json.loads(pilot.read_text(encoding="utf-8", errors="strict"))
            serialized = pilot.read_text(encoding="utf-8", errors="strict")
            if any(marker in serialized for marker in ("\ufffd", "Ã")):
                out.append("ERROR: pilot output contains forbidden U+FFFD or mojibake marker")
            out.append(f"Pilot output: present; distinct lemmas={len({r.get('lemma','').casefold() for r in rows})}; entries={len(rows)}")
            out.append("Ranking formula: freqlemfilms2 + freqlemlivres (films + books lemma frequency); deterministic tie-break: lemma casefold ascending, original lemma ascending, POS casefold ascending.")
            accented_count = sum(1 for row in rows if __import__("re").search(r"[éèêàçù]", row.get("lemma", ""), __import__("re").I) or any(__import__("re").search(r"[éèêàçù]", form.get("form", ""), __import__("re").I) for form in row.get("top_forms", [])))
            out.append(f"Accented output entries (at least one of é, è, ê, à, ç, ù): {accented_count}; minimum required: 20; check: {'PASS' if accented_count >= 20 else 'FAIL'}")
            out.append("\n## First 20 ranked lemmas")
            for i, row in enumerate(rows[:20], 1):
                forms = ", ".join(f"{x.get('form')}({float(x.get('frequency') or 0):.2f})" for x in row.get("top_forms", []))
                out.append(f"{i}. {row.get('lemma')} | lemma_frequency={float(row.get('lemma_frequency') or 0):.2f} | column={row.get('lemma_frequency_column')} | POS={row.get('part_of_speech')} | gender={row.get('gender')} | top_forms={forms}")
            sample = random.Random(42).sample(rows, min(40, len(rows)))
            out.append(f"\n## Random pilot review sample ({len(sample)} lemmas)")
            for row in sample:
                forms = ", ".join(f"{x.get('form')}({float(x.get('frequency') or 0):.2f})" for x in row.get("top_forms", []))
                out.append(f"{row.get('lemma')} | lemma_frequency={float(row.get('lemma_frequency') or 0):.2f} | POS={row.get('part_of_speech')} | gender={row.get('gender')} | top_forms={forms} | source=Lexique 3.83 | licence=CC BY-SA 4.0")
            out.append("\n## Sentinel output validation")
            for word in ("été", "français", "cœur", "garçon", "où", "noël", "à"):
                found = any(word.casefold() == r.get("lemma", "").casefold() or any(word.casefold() == form.get("form", "").casefold() for form in r.get("top_forms", [])) for r in rows)
                out.append(f"{word}: {'present exactly' if found else 'not in ranked pilot (not fabricated)'}")
        except (OSError, ValueError, TypeError) as exc:
            out.append(f"Pilot output could not be read: {type(exc).__name__}: {exc}")
    else:
        out.append("Pilot output: absent; import did not produce a pilot file.")
    if checks.is_file():
        try:
            result = json.loads(checks.read_text(encoding="utf-8", errors="strict"))
            out.append(f"Cross-check output: present; summary={json.dumps(result.get('summary', {}), ensure_ascii=False, sort_keys=True)}")
            probe = result.get("lefff_encoding_probe", {})
            if probe:
                out.append("Lefff probe persisted in cross-check JSON: " + json.dumps(probe, ensure_ascii=False, sort_keys=True))
            for source, detail in result.get("sources", {}).items():
                out.append(f"Cross-check {source}: status={detail.get('status')}; matched_forms={detail.get('matched_count')}; mismatches={detail.get('mismatch_count')}; encoding={detail.get('encoding')}; note={detail.get('note', '')}")
                for form in detail.get("mismatches", [])[:10]:
                    out.append(f"  first mismatch: {form}")
        except (OSError, ValueError, TypeError) as exc:
            out.append(f"Cross-check output could not be read: {type(exc).__name__}: {exc}")
    else:
        out.append("Cross-check output: absent.")
    # Pilot v3 acceptance evidence: full Dicollecte unknown list and first 30 homograph decisions.
    out.append("\\n## Pilot v3 — Dicollecte unknown forms (full list)")
    if checks.is_file():
        try:
            result = json.loads(checks.read_text(encoding="utf-8", errors="strict"))
            dico = result.get("sources", {}).get("Dicollecte", {})
            unknown = dico.get("unknown_forms", dico.get("mismatches", []))
            out.append(f"Unknown form count: {len(unknown)}")
            out.append(json.dumps(unknown, ensure_ascii=False))
        except (OSError, ValueError, TypeError) as exc:
            out.append(f"Dicollecte unknown forms unavailable: {type(exc).__name__}: {exc}")
    ambiguous_path = ROOT / "data/ambiguous-forms.json"
    out.append("\\n## Pilot v3 — ambiguous-form decisions")
    if ambiguous_path.is_file():
        try:
            decisions = json.loads(ambiguous_path.read_text(encoding="utf-8", errors="strict"))
            out.append(f"Ambiguous forms count: {len(decisions)}")
            for index, decision in enumerate(decisions[:30], 1):
                out.append(f"{index}. {json.dumps(decision, ensure_ascii=False, sort_keys=True)}")
        except (OSError, ValueError, TypeError) as exc:
            out.append(f"Ambiguous-form decisions unavailable: {type(exc).__name__}: {exc}")
    else:
        out.append("Ambiguous-form decisions unavailable: generated file is missing.")
    dest = ROOT / "diagnostics/last-run.txt"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out) + "\n", encoding="utf-8", errors="strict")
    print(dest.read_text(encoding="utf-8", errors="strict"))
    return 0

if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"Diagnostics failed: {type(exc).__name__}: {exc}", file=sys.stderr)
        raise SystemExit(1)
