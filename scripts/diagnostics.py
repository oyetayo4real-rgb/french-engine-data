#!/usr/bin/env python3
"""Evidence-only source diagnostics; never performs lossy decoding."""
from __future__ import annotations
import hashlib, json, random, sys, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = [
    ("Lexique 3.83", ROOT / "data/raw/Lexique383.tsv"),
    ("Dicollecte/Grammalecte Hunspell archive", ROOT / "data/raw/hunspell-french-dictionaries-v7.7.zip"),
    ("Lefff 2.1 gzip", ROOT / "data/raw/lefff-2.1.txt.gz"),
]
SENTINELS = ("été", "français", "cœur", "garçon", "où", "à")

def inspect(path: Path, label: str, out: list[str]) -> bytes | None:
    out.append(f"\n## Source: {label}")
    out.append(f"Path: {path.relative_to(ROOT)}")
    if not path.is_file():
        out.append("STATUS: unavailable (file was not downloaded)")
        return None
    raw = path.read_bytes()
    out.append(f"Size bytes: {len(raw)}")
    out.append(f"SHA-256: {hashlib.sha256(raw).hexdigest()}")
    out.append(f"Starts with UTF-8 BOM: {'yes' if raw.startswith(bytes.fromhex('efbbbf')) else 'no'}")
    out.append(f"First 120 bytes hex: {raw[:120].hex(' ')}")
    out.append(f"Bytes >= 0x80: {sum(byte >= 0x80 for byte in raw)}")
    try:
        raw.decode("utf-8-sig", errors="strict")
        out.append("Strict UTF-8 decode succeeds: yes")
    except UnicodeDecodeError as exc:
        out.append(f"Strict UTF-8 decode succeeds: no ({exc})")
    latin = raw.decode("iso-8859-1", errors="strict")
    missing = [s for s in SENTINELS if s.casefold() not in latin.casefold()]
    out.append(f"Latin-1 decode succeeds: yes (Latin-1 maps every byte)")
    out.append(f"Latin-1 contains all sentinels {SENTINELS}: {'yes' if not missing else 'no; missing=' + repr(missing)}")
    return raw

def main() -> int:
    out = ["# Last-run source and pilot diagnostics", "", "This file is generated by GitHub Actions even when the import fails.", "No lossy decoding is used."]
    raw_files = {}
    for label, path in FILES:
        raw_files[label] = inspect(path, label, out)
    zip_path = ROOT / "data/raw/hunspell-french-dictionaries-v7.7.zip"
    out.append("\n## Hunspell archive inventory and .aff evidence")
    if raw_files.get("Dicollecte/Grammalecte Hunspell archive") is None:
        out.append("Archive unavailable; no members can be inspected.")
    else:
        try:
            with zipfile.ZipFile(zip_path) as zf:
                for info in zf.infolist():
                    out.append(f"FILE {info.filename} | size={info.file_size}")
                affs = [info for info in zf.infolist() if info.filename.lower().endswith(".aff")]
                if not affs:
                    out.append("No .aff files found.")
                for info in affs:
                    data = zf.read(info.filename)
                    if data.startswith(bytes.fromhex("efbbbf")):
                        data = data[3:]
                    text = data.decode("iso-8859-1", errors="strict")
                    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
                    out.append(f"\nAFF: {info.filename} | size={info.file_size}")
                    out.append("First 5 lines (BOM stripped; CRLF normalized):")
                    out.extend("  " + line for line in lines[:5])
                    set_lines = [line for line in lines if line.lstrip().lower().startswith("set ") or line.lstrip().lower() == "set"]
                    out.append("SET lines:")
                    out.extend("  " + line for line in set_lines) if set_lines else out.append("  no SET line")
        except (OSError, zipfile.BadZipFile) as exc:
            out.append(f"Archive inspection error: {type(exc).__name__}: {exc}")
    out.append("\n## Encoding decisions from source payload bytes")
    for label, path, compressed in (
        ("Lexique 3.83", ROOT / "data/raw/Lexique383.tsv", False),
        ("Lefff 2.1 decompressed text", ROOT / "data/raw/lefff-2.1.txt.gz", True),
    ):
        if not path.is_file():
            out.append(f"{label}: unavailable; source file missing")
            continue
        try:
            payload = __import__("gzip").decompress(path.read_bytes()) if compressed else path.read_bytes()
            try:
                decoded = payload.decode("utf-8-sig", errors="strict")
                if any(byte >= 0x80 for byte in payload):
                    out.append(f"{label}: selected UTF-8 (strict UTF-8 succeeds and payload contains non-ASCII bytes)")
                else:
                    latin = payload.decode("iso-8859-1", errors="strict")
                    missing = [s for s in SENTINELS if s.casefold() not in latin.casefold()]
                    out.append(f"{label}: " + ("selected ISO-8859-1 (UTF-8 is ASCII-only and all sentinels appear in Latin-1)" if not missing else f"unconfirmed (ASCII-only UTF-8; Latin-1 sentinel missing {missing})"))
            except UnicodeDecodeError as utf_error:
                latin = payload.decode("iso-8859-1", errors="strict")
                missing = [s for s in SENTINELS if s.casefold() not in latin.casefold()]
                out.append(f"{label}: " + ("selected ISO-8859-1 (strict UTF-8 fails; all sentinels appear in Latin-1)" if not missing else f"unconfirmed (strict UTF-8 fails; Latin-1 sentinel missing {missing})"))
        except (OSError, ValueError) as exc:
            out.append(f"{label}: unconfirmed; payload inspection failed: {type(exc).__name__}: {exc}")
    out.append("Dicollecte/Hunspell: encoding is confirmed only by a paired .aff SET declaration; see archive evidence above.")
    out.append("\n## Encoding decision policy")
    out.append("For plain source files: strict UTF-8 + at least one non-ASCII byte => UTF-8; otherwise ISO-8859-1 only if Latin-1 text contains all required sentinels; else unconfirmed.")
    out.append("For Hunspell .dic files, use the paired .aff SET declaration only. If absent, Dicollecte cross-check is unavailable. Hunspell behavior without SET has not been independently confirmed here.")
    pilot = ROOT / "data/pilot-300.json"
    checks = ROOT / "data/cross-checks-300.json"
    out.append("\n## Pilot and cross-check result")
    if pilot.is_file():
        try:
            rows = json.loads(pilot.read_text(encoding="utf-8", errors="strict"))
            out.append(f"Pilot output: present; entries={len(rows)}")
            sample = random.SystemRandom().sample(rows, min(40, len(rows)))
            out.append(f"\n## Random pilot review sample ({len(sample)} entries)")
            for row in sample:
                out.append(f"{row.get('form')} | lemma={row.get('lemma')} | pos={row.get('part_of_speech')} | gender={row.get('gender')} | number={row.get('number')} | freqfilms={row.get('frequency')} | source=Lexique 3.83 | licence=CC BY-SA 4.0 | needs_review={row.get('needs_review')}")
        except (OSError, ValueError, TypeError) as exc:
            out.append(f"Pilot output could not be read: {type(exc).__name__}: {exc}")
    else:
        out.append("Pilot output: absent; import did not produce a pilot file.")
    if checks.is_file():
        try:
            result = json.loads(checks.read_text(encoding="utf-8", errors="strict"))
            out.append(f"Cross-check output: status={result.get('status')}; summary={json.dumps(result.get('summary', {}), ensure_ascii=False, sort_keys=True)}")
            for source, detail in result.get("sources", {}).items():
                out.append(f"Cross-check {source}: status={detail.get('status')}; matched={detail.get('matched_count')}; mismatches={detail.get('mismatch_count')}; note={detail.get('note', '')}")
                for form in detail.get("mismatches", []):
                    out.append(f"  mismatch: {form}")
        except (OSError, ValueError, TypeError) as exc:
            out.append(f"Cross-check output could not be read: {type(exc).__name__}: {exc}")
    else:
        out.append("Cross-check output: absent.")
    dest = ROOT / "diagnostics/last-run.txt"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out) + "\n", encoding="utf-8", errors="strict")
    print(dest.read_text(encoding="utf-8", errors="strict"))
    return 0

if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"Diagnostics failed: {type(exc).__name__}: {exc}", file=sys.stderr)
        raise SystemExit(1)
